    k = np.random.randint(0, n_train - batch_size - 1)

    X_train = x_train[k: k + batch_size]
    Y_train = y_train[k: k + batch_size]

    grad = np.mean([df(w, x, y) for x, y in zip(X_train, Y_train)], axis=0)
    loss_av_k = np.mean([loss(w, x, y) for x, y in zip(X_train, Y_train)], axis=0)
